// Translate the existing, straight-line SPC25 register listing. This is a
// build tool. The browser executes compiled Rust for both robot families.
import { readFile, writeFile } from 'node:fs/promises';

const source = await readFile(new URL('../2_3DSimulation/native-matrix-arithmetic.mjs', import.meta.url), 'utf8');
const output = ['// Generated by simulator-rust/generate-matrix.mjs from the SPC25 register listing.\nuse super::Machine;'];

function expression(value) {
    return value.replaceAll('Math.fround', '')
        .replace(/memory\.getFloat64\(\((.+?)\), true\)/g, 'm.load_double($1)')
        .replace(/fm\[\((.+?)\) >>> 2\]/g, 'f32::from_bits(m.ram[(($1) / 4) as usize])')
        .replace(/\bu\[\((.+?)\) >>> 2\]/g, 'm.ram[(($1) / 4) as usize]')
        .replace(/\bvu\[(\d+)\]/g, 'm.v[$1]')
        .replace(/\bs\[(\d+)\]/g, 'm.single($1)')
        .replace(/\bd\[(\d+)\]/g, 'm.double($1)')
        .replace(/\br\[/g, 'm.r[').replace(/\ba\b/g, 'm.address');
}

function translate(line) {
    if (line.startsWith('cv[0]')) {
        const match = /Math\.(sin|cos)\(cd\[0\]\)/.exec(line);
        if (!match) throw Error('Unknown firmware math call: ' + line);
        return [`m.trig(f64::${match[1]});`];
    }
    return line.split(';').map(s => s.trim()).filter(Boolean).map(statement => {
        let match = /^memory\.setFloat64\(\((.+?)\), (.+?), true\)$/.exec(statement);
        if (match) return `m.store_double(${expression(match[1])}, ${expression(match[2])});`;
        match = /^(.+?) ([-+]?=) (.+)$/.exec(statement);
        if (!match) throw Error('Unknown firmware instruction: ' + statement);
        const [, left, op, right] = match;
        const rhs = expression(right);
        const fp = /^([sd])\[(\d+)\]$/.exec(left);
        if (fp) return fp[1] === 's'
            ? `m.set_single(${fp[2]}, (${rhs}) as f32);`
            : `m.set_double(${fp[2]}, (${rhs}) as f64);`;
        const store = /^fm\[\((.+?)\) >>> 2\]$/.exec(left);
        if (store) return `m.ram[((${expression(store[1])}) / 4) as usize] = (${rhs}).to_bits();`;
        if (!/^(a|(?:r|vu|u)\[.*\])$/.test(left)) throw Error('Unknown destination: ' + left);
        return `${expression(left)} ${op} ${rhs};`;
    });
}

for (const [name, rustName] of [['nativeSixMatrixArithmetic', 'six'], ['nativeScaraMatrixArithmetic', 'scara']]) {
    const match = source.match(new RegExp('export function ' + name + '\\([^\\n]*\\{\\s*let a = 0;([\\s\\S]*?)\\n\\}'));
    if (!match) throw Error('Missing firmware function ' + name);
    const instructions = match[1].trim().split(/\r?\n/).flatMap(line => translate(line.trim()));
    const calls = [];
    for (let start = 0; start < instructions.length; start += 128) {
        const part = rustName + '_' + start;
        calls.push(`    ${part}(m);`);
        output.push(`#[inline(never)]\nfn ${part}(m: &mut Machine) {\n` +
            instructions.slice(start, start + 128).map(s => '    ' + s).join('\n') + '\n}');
    }
    output.push(`pub(super) fn ${rustName}(m: &mut Machine) {\n${calls.join('\n')}\n}`);
}
await writeFile(new URL('./src/generated_matrix.rs', import.meta.url), output.join('\n\n') + '\n');
