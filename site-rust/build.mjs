import { spawnSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(fileURLToPath(import.meta.url));
const target = 'wasm32-unknown-unknown';
for (const [feature, adapter, destination] of [
    ['site', 'browser.js', '../shared/site-engine.js'],
    ['controller', 'controller.js', '../4_ProjectGenerator/generator.js'],
    ['tool', 'tool.js', '../3_ToolSelector/tool-engine.mjs']
]) {
    const build = spawnSync('cargo', ['build', '--locked', '--release', '--target', target,
        '--no-default-features', '--features', feature], { cwd: root, stdio: 'inherit' });
    if (build.error) throw build.error;
    if (build.status !== 0) process.exit(build.status ?? 1);
    const binary = await readFile(path.resolve(root, process.env.CARGO_TARGET_DIR || 'target',
        target, 'release', 'inorobot_site.wasm'));
    // Classic scripts also support offline pages and synchronous export handlers.
    const source = (await readFile(path.join(root, adapter), 'utf8')).replaceAll('\r\n', '\n');
    await writeFile(path.join(root, destination), '// Generated by node site-rust/build.mjs from ' + adapter + '\n' +
        source.replace("'__SITE_WASM__'", () => "'" + binary.toString('base64') + "'"));
}
