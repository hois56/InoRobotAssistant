"""Regenerate the document preview after replacing Remote_IO_List.xlsx (requires openpyxl)."""

from base64 import b64encode
from hashlib import sha256
from html import escape
from pathlib import Path

from openpyxl import load_workbook
from openpyxl.cell.cell import MergedCell


SOURCE = Path(__file__).resolve().parents[1] / "Software_manual" / "Remote_IO_List.xlsx"


def sheet_markup(sheet, section_id):
    # The merged first row introduces the sheet. Row two defines the table columns.
    headings = [cell.value for cell in sheet[2] if cell.value is not None]
    column_count = len(headings)
    header_row = "".join(f'<th scope="col">{escape(title)}</th>' for title in headings)
    row_spans = {
        (area.min_row, area.min_col): area.max_row - area.min_row + 1
        for area in sheet.merged_cells.ranges if area.max_row > area.min_row
    }
    images = {image.anchor._from.row + 1: image for image in sheet._images}
    title = escape(sheet.title)
    lines = [f'<section aria-labelledby="{section_id}">',
             f'<h2 id="{section_id}">{title}</h2>', f'<p>{escape(sheet["A1"].value)}</p>']

    table_open = False
    for row in sheet.iter_rows(min_row=2, max_col=column_count):
        if row[0].value == headings[0]:
            if table_open:
                lines.append('</tbody></table></div>')
            lines.extend([f'<div class="table-scroll" role="region" aria-label="{title}" tabindex="0">',
                          f'<table><thead><tr>{header_row}</tr></thead><tbody>'])
            table_open = True
        elif row[0].row in images:
            if table_open:
                lines.append('</tbody></table></div>')
                table_open = False
            image = images[row[0].row]
            encoded = b64encode(image._data()).decode('ascii')
            lines.append(f'<img src="data:image/{image.format};base64,{encoded}" width="{image.width}" '
                         f'height="{image.height}" alt="현재 위치와 목표 위치, 수동 조그 조작 화면">')
        elif any(cell.value is not None for cell in row):
            cells = []
            for cell in row:
                if isinstance(cell, MergedCell):
                    continue
                span = row_spans.get((cell.row, cell.column), 1)
                attribute = f' rowspan="{span}"' if span > 1 else ''
                value = '' if cell.value is None else escape(str(cell.value).strip())
                cells.append(f'<td{attribute}>{value}</td>')
            lines.append('<tr>' + ''.join(cells) + '</tr>')

    if table_open:
        lines.append('</tbody></table></div>')
    lines.append('</section>')
    return '\n'.join(lines)


def main():
    workbook = load_workbook(SOURCE, data_only=True)
    sheets = [(sheet, f'sheet-{index}') for index, sheet in enumerate(workbook.worksheets, 1)]
    links = '\n'.join(f'<a href="#{target}">{escape(sheet.title)}</a>' for sheet, target in sheets)
    sections = '\n'.join(sheet_markup(sheet, target) for sheet, target in sheets)
    html = f'''<!doctype html>
<!-- Generated by ../design/generate_remote_io_preview.py -->
<html lang="ko">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="workbook-sha256" content="{sha256(SOURCE.read_bytes()).hexdigest()}">
<title>{SOURCE.name} · 문서 미리보기</title>
<link rel="stylesheet" href="../../shared/brand-colors.css?v=20261120-blue">
<link rel="stylesheet" href="../assets/remote-io-preview.css?v=20261120-blue">
</head>
<body>
<main>
<h1>{SOURCE.name}</h1>
<nav aria-label="워크시트">{links}</nav>
{sections}
</main>
</body>
</html>
'''
    SOURCE.with_suffix('.html').write_bytes(html.encode('utf-8'))


if __name__ == '__main__':
    main()
