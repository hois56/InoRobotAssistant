// Prebuilds the Tailwind utilities and Lucide icons used by the Project Generator and Debugging Tool
// pages, so they no longer load the Tailwind Play CDN (a runtime compiler) or the full Lucide bundle.
//
//   node tools/build-tailwind-pages.cjs            rebuild every page group
//   node tools/build-tailwind-pages.cjs project    rebuild one group (project | debugging)
//
// Run it after adding Tailwind classes or data-lucide icons to these pages. It needs network access
// to cdn.tailwindcss.com and unpkg.com, and uses the Chromium installed for Playwright.
const fs = require('fs');
const path = require('path');
const { chromium } = require('@playwright/test');

const root = path.resolve(__dirname, '..');
const TAILWIND_URL = 'https://cdn.tailwindcss.com/3.4.17';
const LUCIDE_URL = 'https://unpkg.com/lucide@0.468.0/dist/umd/lucide.min.js';
const groups = {
    project: {
        outDir: '4_ProjectGenerator',
        sources: ['4_ProjectGenerator/index.html', '4_ProjectGenerator/app.js', '4_ProjectGenerator/project-editor-ui.js',
            '4_ProjectGenerator/project-editor.js', '0_Home/tool-guide-embed.js']
    },
    debugging: {
        outDir: '7_DebuggingTool',
        sources: ['7_DebuggingTool/index.html', '7_DebuggingTool/ZeroCalibration/index.html', '7_DebuggingTool/debugging-history.js']
    }
};

function collect(sources) {
    const tokens = new Set();
    const icons = new Set();
    for (const file of sources) {
        const text = fs.readFileSync(path.join(root, file), 'utf8');
        // Arbitrary values such as bg-[rgba(1,2,3,0.5)] contain commas; keep them whole.
        for (const match of text.matchAll(/(?:[a-z0-9-]+:)*!?-?[a-z][\w-]*-\[[^\]\s"'`<>]+\](?:\/[\w.]+)?/gi)) tokens.add(match[0]);
        for (const raw of text.split(/[\s"'`<>={};\\,]+/)) {
            const token = raw.replace(/^\$\{[^}]*\}/, '').replace(/\)+$/, '');
            if (token.length < 2 || token.length > 80) continue;
            if (/^!?-?[a-z0-9@[][\w:\-/[\].%#!()]*$/i.test(token)) tokens.add(token);
        }
        for (const match of text.matchAll(/data-lucide=["'`]([\w-]+)["'`]/g)) icons.add(match[1]);
        for (const match of text.matchAll(/\bicon\s*:\s*["']([a-z][\w-]*)["']/g)) icons.add(match[1]);
    }
    return { tokens: [...tokens], icons: [...icons].sort() };
}

function iconScript(icons) {
    return `// Generated by tools/build-tailwind-pages.cjs from Lucide 0.468.0 (ISC license).
// Same markup and attributes as lucide.createIcons() for the icons this page uses.
(function () {
    'use strict';
    const ICONS = ${JSON.stringify(icons, null, 4).replace(/\n/g, '\n    ')};
    const DEFAULTS = {
        xmlns: 'http://www.w3.org/2000/svg', width: '24', height: '24', viewBox: '0 0 24 24',
        fill: 'none', stroke: 'currentColor', 'stroke-width': '2', 'stroke-linecap': 'round', 'stroke-linejoin': 'round'
    };

    function createIcons() {
        document.querySelectorAll('[data-lucide]').forEach(function (element) {
            if (element.namespaceURI === 'http://www.w3.org/2000/svg') return;
            const name = element.getAttribute('data-lucide');
            if (!Object.prototype.hasOwnProperty.call(ICONS, name)) return;
            const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
            Object.keys(DEFAULTS).forEach(function (key) { svg.setAttribute(key, DEFAULTS[key]); });
            Array.from(element.attributes).forEach(function (attribute) { svg.setAttribute(attribute.name, attribute.value); });
            svg.setAttribute('class', ['lucide', 'lucide-' + name, element.getAttribute('class') || ''].join(' ').trim());
            svg.innerHTML = ICONS[name];
            element.replaceWith(svg);
        });
    }

    window.lucide = { createIcons: createIcons };
})();
`;
}

async function buildGroup(browser, name, group) {
    const { tokens, icons } = collect(group.sources);
    const page = await browser.newPage();
    await page.setContent('<!doctype html><html><head></head><body><div id="probe"></div></body></html>');
    await page.addScriptTag({ url: TAILWIND_URL });
    await page.evaluate(list => { document.getElementById('probe').className = list.join(' '); }, tokens);
    await page.waitForFunction(() => [...document.querySelectorAll('style')].some(style => style.textContent.includes('--tw-')), null, { timeout: 30000 });
    await page.waitForTimeout(1500);
    const css = await page.evaluate(() => [...document.querySelectorAll('style')].map(style => style.textContent)
        .filter(text => text.includes('--tw-')).sort((a, b) => b.length - a.length)[0]);
    await page.addScriptTag({ url: LUCIDE_URL });
    const markup = await page.evaluate(names => {
        const host = document.createElement('div');
        host.innerHTML = names.map(icon => `<i data-lucide="${icon}"></i>`).join('');
        document.body.append(host);
        window.lucide.createIcons();
        const out = {};
        host.querySelectorAll('svg').forEach(svg => { out[svg.getAttribute('data-lucide')] = svg.innerHTML; });
        return out;
    }, icons);
    await page.close();
    const missing = icons.filter(icon => !markup[icon]);
    if (missing.length) throw new Error(`${name}: unknown Lucide icons ${missing.join(', ')}`);
    const header = '/* Generated by tools/build-tailwind-pages.cjs with Tailwind CSS v3.4.17 (default config)\n'
        + '   for the classes used on this page. Do not edit; rerun the tool after adding classes. */\n';
    fs.writeFileSync(path.join(root, group.outDir, 'tailwind.css'), header + css + '\n');
    fs.writeFileSync(path.join(root, group.outDir, 'icons.js'), iconScript(markup));
    console.log(`${name}: ${tokens.length} candidate classes, ${css.length} bytes CSS, ${icons.length} icons`);
}

(async () => {
    const selected = process.argv.slice(2);
    const names = selected.length ? selected : Object.keys(groups);
    const unknown = names.filter(name => !groups[name]);
    if (unknown.length) throw new Error('Unknown group: ' + unknown.join(', '));
    const browser = await chromium.launch();
    try {
        for (const name of names) await buildGroup(browser, name, groups[name]);
    } finally {
        await browser.close();
    }
})().catch(error => {
    console.error(error.message);
    process.exitCode = 1;
});
